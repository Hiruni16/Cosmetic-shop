    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        try{
        String productId = txtProductID.getText().trim();

        String sql = "SELECT Product ID, Product ame, Stocks FROM product WHERE Product ID = ?";
        ps = con.prepareStatement(sql);
        ps.setString(1, productId); 
        ResultSet rs = ps.executeQuery();

        DefaultTableModel model = new DefaultTableModel();
        tblStocks.setModel(model);

        model.addColumn("Product ID");
        model.addColumn("Product Name");
        model.addColumn("Stocks");

        if (rs.next()) {
            String productName = rs.getString("Product_Name");
            int stocks = rs.getInt("Stocks");

            model.addRow(new Object[]{productId, productName, stocks});
        } else {
            JOptionPane.showMessageDialog(this, "Product ID not found", "Error", JOptionPane.ERROR_MESSAGE);
                
            }
        }catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Product ID not found");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

