    private void Register() {
        try {
            String userID = txtUserID.getText();
            String name = txtName.getText();
            String contactNo = txtContactNo.getText();
            String email = txtEmail.getText();
            String usName = txtUsName.getText();
            String pw = String.valueOf(txtPw.getText());

            if (userID.isEmpty() || name.isEmpty() || contactNo.isEmpty() || email.isEmpty() || usName.isEmpty() || pw.isEmpty()) {
                JOptionPane.showMessageDialog(this, "All fields are required!");
                return;
            }

            if (!email.toLowerCase().endsWith("@gmail.com")) {
                JOptionPane.showMessageDialog(this, "Email must end with '@gmail.com'!");
                return;
            }

            if (pw.length() < 10) {
                JOptionPane.showMessageDialog(this, "Password must have at least 10 characters!");
                return;
            }
            String checkSql = "SELECT * FROM user WHERE UserID = ?";
            ps = con.prepareStatement(checkSql);
            ps.setString(1, userID);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "User ID already exists! Please enter a different ID.");
            } else {
                
                String sql = "INSERT INTO user VALUES (?, ?, ?, ?, ?, ?)";
                ps = con.prepareStatement(sql);

                ps.setString(1, userID);
                ps.setString(2, name);
                ps.setString(3, contactNo);     
                ps.setString(4, email);
                ps.setString(5, usName);
                ps.setString(6, pw);

                if (ps.executeUpdate() > 0) {
                    JOptionPane.showMessageDialog(this, "User Record Inserted!");
                    clear();
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
     
    }

