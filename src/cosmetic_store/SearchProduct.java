    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        try{
            String productID = (txtProductID.getText());
            String sql = "Select * from Product WHARE ProductID = ? OR Product Name = ? OR Category = ? OR Price = ? OR Stocks = ?";
            
            ps = con.prepareStatement(sql);
            
            ps.setString(1, productID);
            ps.setString(2, productID);
            ps.setString(3, productID);
            ps.setString(4, productID);
            
            ResultSet rs = ps.executeQuery();
            if (rs.isBeforeFirst()) {
                rs.first();
                txtProductName.setText(rs.getString("ProductName"));
                cmbCategory.setText(rs.getString("Category"));
                txtPrice.setText(rs.getString("Price"));
                txtStocks.setText(rs.getString("Stocks"));
            }else{
                 JOptionPane.showMessageDialog(this, " Not Found!");
                clear();
            }
            
        }catch (Exception e) {
            e.printStackTrace();
        }  
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnRefreshActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRefreshActionPerformed
         try {
        String sql = "SELECT Product ID, Product Name, Category, Price, Stocks FROM product WHERE Stocks > 0";
        ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        
        DefaultTableModel model = new DefaultTableModel();
        tblProducts.setModel(model);

        
        model.addColumn("Product ID");
        model.addColumn("Product Name");
        model.addColumn("Category");
        model.addColumn("Price");
        model.addColumn("Stocks");

        
        while (rs.next()) {
            String productId = rs.getString("Product ID");
            String productName = rs.getString("Product Name");
            String category = rs.getString("Category");
            Double price = rs.getDouble("Price");
            int stocks = rs.getInt("Stocks");

            
            model.addRow(new Object[]{productId, productName, category, price, stocks});
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnRefreshActionPerformed

